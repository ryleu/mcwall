"""Shell completion, generated from the parser rather than written by hand.

A completion script is a second description of the command surface, and the
usual fate of a second description is to drift from the first. These are
produced from the same `build_parser()` the CLI parses with, so a command or
flag appears in the shell the moment it exists in the code.
"""

from __future__ import annotations


def _leaves(parser, prefix: tuple[str, ...] = ()) -> dict[tuple[str, ...], list[str]]:
    """Every runnable command path, mapped to its option flags."""
    group = next(
        (a for a in parser._actions
         if getattr(a, "choices", None) and hasattr(a, "add_parser")),
        None,
    )
    if group is None:
        flags = [f for a in parser._actions for f in a.option_strings]
        return {prefix: sorted(flags)}

    found: dict[tuple[str, ...], list[str]] = {}
    for name, sub in group.choices.items():
        found.update(_leaves(sub, prefix + (name,)))
    return found


def _groups(leaves) -> dict[tuple[str, ...], list[str]]:
    """Each prefix that is a group, mapped to the words that may follow it."""
    groups: dict[tuple[str, ...], set[str]] = {}
    for path in leaves:
        for depth in range(len(path)):
            groups.setdefault(path[:depth], set()).add(path[depth])
    return {prefix: sorted(words) for prefix, words in groups.items()}


def bash(parser) -> str:
    leaves = _leaves(parser)
    groups = _groups(leaves)

    lines = [
        "# mcwall bash completion, generated by `mcwall --completion bash`",
        "_mcwall() {",
        '    local cur prev words cword',
        '    COMPREPLY=()',
        '    cur="${COMP_WORDS[COMP_CWORD]}"',
        # The command path is every non-flag word after the program name.
        '    local path=""',
        '    local w',
        '    for w in "${COMP_WORDS[@]:1:COMP_CWORD-1}"; do',
        '        [[ "$w" == -* ]] && continue',
        '        path="${path:+$path }$w"',
        '    done',
        '    case "$path" in',
    ]
    for prefix, words in sorted(groups.items(), key=lambda kv: -len(kv[0])):
        lines.append('        "%s")' % " ".join(prefix))
        lines.append(f'            COMPREPLY=($(compgen -W "{" ".join(words)}" -- "$cur")); return;;')
    for path, flags in sorted(leaves.items(), key=lambda kv: -len(kv[0])):
        if not flags:
            continue
        lines.append('        "%s")' % " ".join(path))
        lines.append(f'            COMPREPLY=($(compgen -W "{" ".join(flags)}" -- "$cur")); return;;')
    lines += [
        "    esac",
        "}",
        "complete -F _mcwall mcwall",
        "",
    ]
    return "\n".join(lines)


def zsh(parser) -> str:
    leaves = _leaves(parser)
    groups = _groups(leaves)

    def describe(parser_for, names):
        group = next(
            (a for a in parser_for._actions
             if getattr(a, "choices", None) and hasattr(a, "add_parser")),
            None,
        )
        helps = {
            a.dest: (a.help or "").replace("'", "")
            for a in getattr(group, "_choices_actions", [])
        } if group else {}
        return [f"{name}:{helps.get(name, '')}" for name in names]

    def walk(parser_for, prefix):
        group = next(
            (a for a in parser_for._actions
             if getattr(a, "choices", None) and hasattr(a, "add_parser")),
            None,
        )
        out = {}
        if group is not None:
            out[prefix] = describe(parser_for, sorted(group.choices))
            for name, sub in group.choices.items():
                out.update(walk(sub, prefix + (name,)))
        return out

    described = walk(parser, ())

    lines = [
        "#compdef mcwall",
        "# generated by `mcwall --completion zsh`",
        "_mcwall() {",
        "    local -a path",
        "    local w",
        '    for w in "${words[@]:1:$((CURRENT-2))}"; do',
        '        [[ "$w" == -* ]] && continue',
        "        path+=($w)",
        "    done",
        '    local key="${(j: :)path}"',
        '    case "$key" in',
    ]
    for prefix, entries in sorted(described.items(), key=lambda kv: -len(kv[0])):
        joined = " ".join(f"'{e}'" for e in entries)
        lines.append('        "%s")' % " ".join(prefix))
        lines.append(f"            _describe 'command' \"({joined})\" && return;;")
    for path, flags in sorted(leaves.items(), key=lambda kv: -len(kv[0])):
        if not flags:
            continue
        lines.append('        "%s")' % " ".join(path))
        lines.append(f"            _values 'option' {' '.join(flags)} && return;;")
    lines += [
        "    esac",
        "}",
        "_mcwall \"$@\"",
        "",
    ]
    return "\n".join(lines)


SHELLS = {"bash": bash, "zsh": zsh}


def render(parser, shell: str) -> str:
    try:
        return SHELLS[shell](parser)
    except KeyError:
        raise SystemExit(f"no completion for {shell!r}; try: {', '.join(SHELLS)}")
