"""Shell completion, generated from the parser rather than written by hand.

A completion script is a second description of the command surface, and the
usual fate of a second description is to drift from the first. These are
produced from the same `build_parser()` the CLI parses with, so a command or
flag appears in the shell the moment it exists in the code.
"""

from __future__ import annotations


# What a positional should offer. `path` takes a build id or any directory
# holding a manifest, so it completes as both; `world` is a save name.
POSITIONALS = {
    "path": ("builds", True),
    "world": ("worlds", False),
}


_positional_dests: dict = {}


def _subparser_group(parser):
    """The `add_subparsers` action of a parser, or None if it is a leaf."""
    return next(
        (a for a in parser._actions
         if getattr(a, "choices", None) and hasattr(a, "add_parser")),
        None,
    )


def _positionals(parser) -> list[str]:
    return [a.dest for a in parser._actions if not a.option_strings and a.dest != "help"]


def _leaves(parser, prefix: tuple[str, ...] = ()) -> dict[tuple[str, ...], list[str]]:
    """Every runnable command path, mapped to its option flags."""
    group = _subparser_group(parser)
    if group is None:
        flags = [f for a in parser._actions for f in a.option_strings]
        return {prefix: sorted(flags)}

    found: dict[tuple[str, ...], list[str]] = {}
    for name, sub in group.choices.items():
        found.update(_leaves(sub, prefix + (name,)))
    return found


def _groups(leaves) -> dict[tuple[str, ...], list[str]]:
    """Each prefix that is a group, mapped to the words that may follow it."""
    groups: dict[tuple[str, ...], set[str]] = {}
    for path in leaves:
        for depth in range(len(path)):
            groups.setdefault(path[:depth], set()).add(path[depth])
    return {prefix: sorted(words) for prefix, words in groups.items()}


def _collect_positionals(parser, prefix=()):
    group = _subparser_group(parser)
    if group is None:
        return {prefix: _positionals(parser)}
    found = {}
    for name, sub in group.choices.items():
        found.update(_collect_positionals(sub, prefix + (name,)))
    return found


def _group_flags(parser, prefix=()) -> dict:
    """Option flags belonging to each node that is a group of subcommands.

    `_leaves` stops at a group and recurses, so without this the flags on
    `mcwall` itself and on `mcwall world` are never offered anywhere — the
    root knows `--completion` and nothing can complete it.
    """
    group = _subparser_group(parser)
    if group is None:
        return {}
    found = {prefix: sorted(f for a in parser._actions for f in a.option_strings)}
    for name, sub in group.choices.items():
        found.update(_group_flags(sub, prefix + (name,)))
    return found


def _value_flags(parser) -> list[str]:
    """Every flag anywhere that consumes a following word.

    The command path is read by dropping words that start with `-`, which
    silently keeps the *value* of such a flag: after `--limit 5` the path
    becomes "world render 5" and matches no branch, so completion dies the
    moment an option with a value is on the line.
    """
    found: set[str] = set()

    def walk(node):
        for action in node._actions:
            if not action.option_strings or hasattr(action, "add_parser"):
                continue
            if action.nargs != 0:
                found.update(action.option_strings)
        group = _subparser_group(node)
        if group is not None:
            for sub in group.choices.values():
                walk(sub)

    walk(parser)
    return sorted(found)


def _choice_flags(parser) -> dict:
    """Flags whose argument argparse already knows the values of.

    Taken from the parser for the same reason the commands are: `--weather`
    gains a value in the shell the moment `Weather` gains a member.
    """
    found: dict[str, set] = {}

    def walk(node):
        for action in node._actions:
            if not action.option_strings or hasattr(action, "add_parser"):
                continue
            if getattr(action, "choices", None):
                for flag in action.option_strings:
                    found.setdefault(flag, set()).update(str(c) for c in action.choices)
        group = _subparser_group(node)
        if group is not None:
            for sub in group.choices.values():
                walk(sub)

    walk(parser)
    return {flag: sorted(values) for flag, values in found.items()}


def bash(parser) -> str:
    global _positional_dests
    _positional_dests = _collect_positionals(parser)
    leaves = _leaves(parser)
    groups = _groups(leaves)

    group_flags = _group_flags(parser)
    value_flags = _value_flags(parser)
    choice_flags = _choice_flags(parser)

    lines = [
        "# mcwall bash completion, generated by `mcwall --completion bash`",
        "_mcwall() {",
        '    local cur prev',
        '    COMPREPLY=()',
        '    cur="${COMP_WORDS[COMP_CWORD]}"',
        '    prev="${COMP_WORDS[COMP_CWORD-1]}"',
    ]
    if choice_flags:
        # Before anything else: the word after one of these is its value, not
        # a command.
        lines.append('    case "$prev" in')
        for flag, values in sorted(choice_flags.items()):
            lines.append(f'        {flag})')
            lines.append(
                f'            COMPREPLY=($(compgen -W "{" ".join(values)}" -- "$cur")); return;;'
            )
        lines.append("    esac")
    lines += [
        # The command path is every word after the program name that is
        # neither a flag nor the value of one. Dropping only the flags would
        # leave "world render 5" after `--limit 5`, which matches no branch.
        '    local path="" w skip=0',
        '    for w in "${COMP_WORDS[@]:1:COMP_CWORD-1}"; do',
        '        if [[ $skip == 1 ]]; then skip=0; continue; fi',
        '        case "$w" in',
    ]
    if value_flags:
        lines.append(f'            {"|".join(value_flags)}) skip=1; continue;;')
    lines += [
        '            -*) continue;;',
        '        esac',
        '        path="${path:+$path }$w"',
        '    done',
        '    case "$path" in',
    ]
    for prefix, words in sorted(groups.items(), key=lambda kv: -len(kv[0])):
        # A group offers its subcommands and its own flags: `--completion`
        # lives on the root, which is a group and nothing else.
        offered = sorted(set(words) | set(group_flags.get(prefix, [])))
        lines.append('        "%s")' % " ".join(prefix))
        lines.append(f'            COMPREPLY=($(compgen -W "{" ".join(offered)}" -- "$cur")); return;;')
    for path, flags in sorted(leaves.items(), key=lambda kv: -len(kv[0])):
        words = list(flags)
        kind = dirs = None
        for dest in _positional_dests.get(path, []):
            if dest in POSITIONALS:
                kind, dirs = POSITIONALS[dest]
        if not words and kind is None:
            continue
        lines.append('        "%s")' % " ".join(path))
        if kind:
            # Read names line by line: "New World" is one suggestion, and
            # `compgen -W` would split it into two. printf %q quotes the
            # space so the completed word is usable as typed.
            lines += [
                "            local -a _names",
                f'            mapfile -t _names < <(mcwall --complete {kind} 2>/dev/null)',
                '            local _n',
                '            for _n in "${_names[@]}"; do',
                '                [[ "$_n" == "$cur"* ]] && COMPREPLY+=("$(printf %q "$_n")")',
                "            done",
            ]
            if words:
                lines.append(
                    f'            COMPREPLY+=($(compgen -W "{" ".join(words)}" -- "$cur"))'
                )
            if dirs:
                lines.append('            COMPREPLY+=($(compgen -d -- "$cur"))')
            lines.append("            return;;")
        else:
            lines.append(
                f'            COMPREPLY=($(compgen -W "{" ".join(words)}" -- "$cur")); return;;'
            )
    lines += [
        "    esac",
        "}",
        "complete -F _mcwall mcwall",
        "",
    ]
    return "\n".join(lines)


def zsh(parser) -> str:
    global _positional_dests
    _positional_dests = _collect_positionals(parser)
    leaves = _leaves(parser)
    groups = _groups(leaves)

    def describe(parser_for, names):
        group = next(
            (a for a in parser_for._actions
             if getattr(a, "choices", None) and hasattr(a, "add_parser")),
            None,
        )
        helps = {
            a.dest: (a.help or "").replace("'", "")
            for a in getattr(group, "_choices_actions", [])
        } if group else {}
        return [f"{name}:{helps.get(name, '')}" for name in names]

    def walk(parser_for, prefix):
        group = next(
            (a for a in parser_for._actions
             if getattr(a, "choices", None) and hasattr(a, "add_parser")),
            None,
        )
        out = {}
        if group is not None:
            out[prefix] = describe(parser_for, sorted(group.choices))
            for name, sub in group.choices.items():
                out.update(walk(sub, prefix + (name,)))
        return out

    described = walk(parser, ())

    group_flags = _group_flags(parser)
    value_flags = _value_flags(parser)
    choice_flags = _choice_flags(parser)

    lines = [
        "#compdef mcwall",
        "# generated by `mcwall --completion zsh`",
        "_mcwall() {",
    ]
    if choice_flags:
        lines.append('    case "${words[CURRENT-1]}" in')
        for flag, values in sorted(choice_flags.items()):
            lines.append(f"        {flag})")
            lines.append(f"            local -a _vals; _vals=({' '.join(values)})")
            lines.append("            _describe 'value' _vals && return;;")
        lines.append("    esac")
    lines += [
        # NOT `path`: in zsh that array is tied to $PATH, so filling it with
        # the command words empties PATH for the rest of the function and
        # every `mcwall --complete ...` below returns nothing. Commands and
        # flags still complete, which is why this hid for so long.
        "    local -a _cmdpath",
        "    local _w",
        "    integer _skip=0",
        '    for _w in "${words[@]:1:$((CURRENT-2))}"; do',
        "        if (( _skip )); then _skip=0; continue; fi",
        "        case $_w in",
    ]
    if value_flags:
        lines.append(f"            ({'|'.join(value_flags)}) _skip=1; continue;;")
    lines += [
        "            (-*) continue;;",
        "        esac",
        "        _cmdpath+=($_w)",
        "    done",
        '    local _key="${(j: :)_cmdpath}"',
        '    case "$_key" in',
    ]
    for prefix, entries in sorted(described.items(), key=lambda kv: -len(kv[0])):
        joined = " ".join(f"'{e}'" for e in entries)
        lines.append('        "%s")' % " ".join(prefix))
        lines.append(f"            _describe 'command' \"({joined})\"")
        own = group_flags.get(prefix, [])
        if own:
            lines.append(f"            _values 'option' {' '.join(own)}")
        lines.append("            return;;")
    for path, flags in sorted(leaves.items(), key=lambda kv: -len(kv[0])):
        kind = dirs = None
        for dest in _positional_dests.get(path, []):
            if dest in POSITIONALS:
                kind, dirs = POSITIONALS[dest]
        if not flags and kind is None:
            continue
        lines.append('        "%s")' % " ".join(path))
        if kind:
            lines += [
                "            local -a _names",
                f'            _names=(${{(f)"$(mcwall --complete {kind} 2>/dev/null)"}})',
                "            _describe -t names 'name' _names",
            ]
            if dirs:
                lines.append("            _files -/")
            if flags:
                lines.append(f"            _values 'option' {' '.join(flags)}")
            lines.append("            return;;")
        else:
            lines.append(f"            _values 'option' {' '.join(flags)} && return;;")
    lines += [
        "    esac",
        "}",
        "_mcwall \"$@\"",
        "",
    ]
    return "\n".join(lines)


SHELLS = {"bash": bash, "zsh": zsh}


def render(parser, shell: str) -> str:
    try:
        return SHELLS[shell](parser)
    except KeyError:
        raise SystemExit(f"no completion for {shell!r}; try: {', '.join(SHELLS)}")
